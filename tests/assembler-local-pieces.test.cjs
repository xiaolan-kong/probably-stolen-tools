const assert=require('node:assert/strict'),fs=require('node:fs');
const A=require('../dist/assets/assembler-joint.js');
const pl=(key,x=0)=>({key,x,y:0,rotation:0,flipped:false});
const piece=(key,owner,extra={})=>({key,machineKey:owner,identifier:'node_medium',kind:'node',base:{performance:0,efficiency:0,quality:0},shape:{width:1,height:1,cells:[{x:0,y:0}]},effects:[],allowed:['moisture_farm'],reason:'',...extra});
const m1={key:'m1',identifier:'moisture_farm',blocked:'0',installed:[pl('a'),pl('b',1)]};
const m2={...m1,key:'m2',installed:[pl('c')]};
const m3={...m1,key:'locked',installed:[pl('locked-piece')]};
const snapshot={machines:[m1,m2,m3],pieces:[piece('a','m1'),piece('b','m1'),piece('c','m2'),piece('free',null),piece('locked-piece','locked'),piece('different','m1',{variantIdentity:'different'}),piece('bad','m1',{reason:'不可用'})]};
const options={borrow:true,locks:['locked'],targets:{moisture_farm:{primary:'quality'}}};
const swapped={machines:{m1:{placements:[pl('c'),pl('free',1)]},m2:{placements:[pl('a')]}}};
const original=JSON.stringify(swapped);
const normalized=A.preferLocalPieces(snapshot,[m1,m2],options,swapped);
assert.deepEqual(normalized.machines.m1.placements,m1.installed);
assert.deepEqual(normalized.machines.m2.placements,m2.installed);
assert.equal(JSON.stringify(swapped),original,'Do not mutate search candidates');
assert.deepEqual(A.preferLocalPieces(snapshot,[m1,m2],options,normalized),normalized,'Stable repeated normalization');
const one={machines:{m1:{placements:[pl('free'),pl('different',1)]}}};
const own=A.preferLocalPieces(snapshot,[m1],options,one);
assert.equal(own.machines.m1.placements[0].key,'a');
assert.equal(own.machines.m1.placements[1].key,'different','Preserve variant effects/identity');
assert.throws(()=>A.preferLocalPieces(snapshot,[m1,m2],{...options,borrow:false},swapped),/不可用/);
const shortage={machines:{m2:{placements:[pl('c'),pl('a',1)]}}};
assert.deepEqual(A.preferLocalPieces(snapshot,[m2],options,shortage).machines.m2.placements.map(p=>p.key),['c','free'],'Free inventory before borrowing');
const actions=A.assemblyActions({...m1,installed:[pl('a'),pl('b',1),pl('c',2)]},{placements:[pl('a'),pl('b',3),pl('free',2)]});
assert.deepEqual(Object.fromEntries(Object.entries(actions).map(([k,v])=>[k,v.map(p=>p.key)])),{out:['c'],move:['b'],in:['free'],stay:['a']});
const originalSnapshot=JSON.stringify(snapshot),finish={machines:{m1:{placements:[pl('c'),pl('a',1)]}}};
const completed=A.completeAssembly({...snapshot,storage:[{key:'counter',label:'柜台'}]},[m1],options,finish,{b:{storageKey:'counter',storageSlot:'[2,3]'}});
assert.equal(JSON.stringify(snapshot),originalSnapshot,'Completion must not mutate imported state');
assert.deepEqual(completed.machines[0].installed,finish.machines.m1.placements);
assert.deepEqual(completed.machines[1].installed,[],'Remove borrowed pieces from donor baseline');
assert.equal(completed.pieces.find(p=>p.key==='c').machineKey,'m1');
assert.equal(completed.pieces.find(p=>p.key==='a').position,'(2, 1)');
assert.equal(completed.pieces.find(p=>p.key==='b').source,'柜台');
assert.equal(completed.pieces.find(p=>p.key==='b').machineKey,null);
const nextPool=A.availablePieces(completed,completed.machines[1],['m1','locked'],true).map(p=>p.key);
assert(!nextPool.includes('a')&&!nextPool.includes('c'),'Completed locked machine and its imported pieces stay reserved');
assert(nextPool.includes('b'),'Removed piece with a recorded location can be reused');
assert.deepEqual(completed.machines[0].current,A.evaluate(completed.machines[0],completed.pieces,completed.machines[0].installed));
const unknown=A.completeAssembly(snapshot,[m1],options,finish);
assert(A.availablePieces(unknown,unknown.machines[1],['m1'],true).every(p=>p.key!=='b'),'Unknown removed location cannot be silently reused');
assert.throws(()=>A.completeAssembly(snapshot,[m1],{...options,locks:['m1']},finish),/锁定/);
if(process.argv[2]){
 const s=A.readSave(fs.readFileSync(process.argv[2],'utf8')),machines=s.machines.filter(m=>m.identifier==='moisture_farm');
 const found=require('./native-planner.cjs').search(s,machines,{...options,locks:[],rounds:240,targets:{moisture_farm:{primary:'quality',secondary:'performance',preferred:150}}});
 const opts={...options,locks:[]},fixed=A.preferLocalPieces(s,machines,opts,found.best);
 const borrowed=c=>Object.entries(c.machines).reduce((n,[key,p])=>n+p.placements.filter(pl=>{const owner=s.pieces.find(p=>p.key===pl.key).machineKey;return owner&&owner!==key;}).length,0);
 for(const m of machines)for(const k of ['performance','efficiency','quality','power','output','tier'])assert.equal(fixed.machines[m.key].evaluation[k],found.best.machines[m.key].evaluation[k]);
 assert(borrowed(fixed)<=borrowed(found.best));
 console.log('Real save: borrowed before/after',borrowed(found.best),borrowed(fixed),'summary',A.jointSummary(machines,fixed,opts));
}
console.log('PASS own instances, original slots, joint reservation, free inventory, lock/borrow boundaries, variants, unchanged effects');
